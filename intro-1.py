def credit_thanks(seed: str) -> str:
    return _pick(CREDIT_THANKS, seed, "thanks")


def credit_final(seed: str) -> str:
    return _pick(CREDIT_FINAL, seed, "final")


def credits(seats: int, stats: dict, seed: str) -> list[str]:
    """Строки титров. stats: deals, lies, refusals (числа за матч). В строках только {0}, {1}, {2}."""
    table = ", ".join("{" + str(i) + "}" for i in range(seats))
    lines = [CREDITS_TITLE, f"За столом: {table}."]
    deals, lies, refusals = int(stats.get("deals", 0)), int(stats.get("lies", 0)), int(stats.get("refusals", 0))
    lines.append(f"Выдач: {deals}. Неправды: {lies}. Отказов: {refusals}.")
    roles = sorted(range(len(CREDIT_ROLES)), key=lambda k: zlib.crc32(f"{seed}:role{k}".encode()))[:3]
    for k in sorted(roles):
        name, values = CREDIT_ROLES[k]
        lines.append(f"{name}: {_pick(values, seed, 'v' + name)}.")
    lines.append(credit_thanks(seed))
    lines.append(credit_final(seed))
    return lines
