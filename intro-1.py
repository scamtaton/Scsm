def _pick(pool: list[str], seed: str, salt: str = "") -> str:
    return pool[zlib.crc32(f"{seed}:{salt}".encode()) % len(pool)]


def _minutes(seconds: float) -> str:
    m = max(1, int(round(seconds / 60)))
    return f"{m} мин"


def intro_text(seats: int, seed: str = "") -> str:
    """Текст вступления. seats: 2 (дуэль) или 3 (стол на троих)."""
    return _pick(INTRO_TRIO if seats == 3 else INTRO_DUEL, seed, f"intro{seats}")


def wait_text(left: float, seed: str = "") -> str:
    return _pick(WAIT_LINES, seed, "wait").format(minutes=_minutes(max(left, 60.0)))


def start_text(seed: str = "") -> str:
    return _pick(START_LINES, seed, "start")


def draw_text(who: list[str] | str, seed: str = "") -> str:
    """Сообщение о технической ничьей. who: имена тех, кто не ответил."""
    names = who if isinstance(who, str) else ", ".join(who)
    return _pick(DRAW_LINES, seed, "draw").format(who=names or "никто")


