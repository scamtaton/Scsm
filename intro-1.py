class Ready:
    """Кто уже нажал «Принять». Отказа нет. Истёк срок и кто-то не нажал: техническая ничья."""

    def __init__(self, seats: int, clock=time.monotonic, seconds: float = READY_SECONDS, auto: tuple = ()):
        self.seats = seats
        self.clock = clock
        self.seconds = float(seconds)
        self.t0 = clock()
        self.ok = [i in auto for i in range(seats)]

    def accept(self, i: int) -> bool:
        """True, если ответ принят сейчас. Повторное нажатие и чужое место ничего не меняют."""
        if not 0 <= i < self.seats or self.ok[i] or self.expired():
            return False
        self.ok[i] = True
        return True

    @property
    def all_ready(self) -> bool:
        return all(self.ok)

    def missing(self) -> list[int]:
        return [i for i in range(self.seats) if not self.ok[i]]

    def left(self) -> float:
        return max(0.0, self.seconds - (self.clock() - self.t0))

    def expired(self) -> bool:
        return not self.all_ready and self.left() <= 0

    def to_dict(self) -> dict:
        return {"seats": self.seats, "ok": list(self.ok), "left": self.left(), "seconds": self.seconds}

    @classmethod
    def from_dict(cls, d: dict, clock=time.monotonic) -> "Ready":
        r = cls(d["seats"], clock=clock, seconds=d.get("seconds", READY_SECONDS))
        r.ok = [bool(x) for x in d["ok"]]
        r.t0 = clock() - (r.seconds - float(d.get("left", r.seconds)))      # время между сохранением и восстановлением не идёт
        return r


