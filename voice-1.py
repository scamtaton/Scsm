_LIST_FIELDS = ("lie_run", "true_run", "kind_n", "quick_run", "refuse_run", "take_run",
                "lies", "truths", "refusals", "takes", "round_dmg", "round_min", "round_start")
_STR_FIELDS = ("kind", "tails")
_SCALAR_FIELDS = ("calls", "last_cycle", "last_series", "round_n", "n_total", "last_hit", "hit_run", "quiet",
                  "round_ex")

_RECENT: deque = deque(maxlen=40)         # недавно сказанные фразы: между матчами по возможности не повторяем


class OpState:
    """Что оператор помнит про матч. seats: 2 (дуэль) или 3 (стол на троих)."""

    def __init__(self, seats: int, seed: str):
        self.seats = seats
        self.seed = str(seed)
        self.calls = 0                    # счётчик бросков: из него и seed выходит повторяемая «случайность»
        self.used: dict[str, list[int]] = {}
        self.fired: set[str] = set()
        self.last_cycle = -99
        self.last_series = -99
        self.round_n = 0
        self.n_total = 0
        z = [0] * seats
        self.lie_run, self.true_run, self.kind_n, self.quick_run = list(z), list(z), list(z), list(z)
        self.refuse_run, self.take_run = list(z), list(z)
        self.lies, self.truths, self.refusals, self.takes = list(z), list(z), list(z), list(z)
        self.kind = [""] * seats          # вид последней лжи: b2c | c2b
        self.tails = [""] * seats         # последние четыре выдачи места: L (ложь) / H (правда)
        self.last_hit = -1
        self.hit_run = 0
        self.quiet = 0
        self.round_ex = 0
        self.round_dmg = list(z)
        self.round_min = list(z)
        self.round_start = list(z)        # рассудок каждого места в начале курса

    def to_dict(self) -> dict:
        d = {k: getattr(self, k) for k in _SCALAR_FIELDS}
        for k in _LIST_FIELDS + _STR_FIELDS:
            d[k] = list(getattr(self, k))
        d["seed"] = self.seed
        d["used"] = {k: list(v) for k, v in self.used.items()}
        d["fired"] = sorted(self.fired)
        return d

    @classmethod
    def from_dict(cls, d: dict | None, seats: int, seed: str) -> "OpState":
        o = cls(seats, (d or {}).get("seed", seed))
        if not d:
            return o
        for k in _SCALAR_FIELDS:
            if k in d:
                setattr(o, k, d[k])
        for k in _LIST_FIELDS + _STR_FIELDS:
            if k in d and len(d[k]) == seats:
                setattr(o, k, list(d[k]))
        o.used = {k: list(v) for k, v in (d.get("used") or {}).items()}
        o.fired = set(d.get("fired") or [])
        return o


