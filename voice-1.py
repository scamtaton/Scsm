"""Голос оператора: короткие реплики, которыми запись комментирует происходящее за столом.

Про Telegram и про движок здесь ничего не известно. Движок (engine.py, trio.py) после каждого события
отдаёт сюда «снимок» (Ex, предмет, конец курса...), а отсюда получает строку или None. Строку движок
кладёт в журнал партии с префиксом NOTE_MARK, и бот рисует её курсивом, как примечания оператора.
Модуль не импортирует engine: engine импортирует его.

Как это устроено
  Счётчики (OpState). Ведутся по местам: сколько лживых выдач подряд, каких именно («горькая названа
    чистой» и «чистая названа горькой» считаются отдельно), правдивых подряд, отказов и согласий подряд,
    потерь подряд, тихих выдач подряд. Всё хранится в to_dict/from_dict, так что /restore память
    оператора не сбрасывает.
  Триггеры (after_exchange и соседи). У каждого есть вес (чем выше, тем важнее), шанс и, если нужно,
    ключ «один раз». Из подходящих говорит один, самый важный из тех, у кого выпал шанс: оператор не болтает.
  Темп. Вес 8 и выше (три лживые выдачи подряд, пятая подряд, курс закрыт Распиской) говорит всегда.
    Остальное: не в соседних циклах выдачи и не больше ROUND_CAP реплик за курс.
  Повторы. Внутри матча фраза из пула не повторится, пока не кончится весь пул; между матчами недавние
    фразы пропускаются (_RECENT).

Настройка (переменные окружения)
  OPERATOR_VOICE=0    оператор молчит совсем
  OPERATOR_CHANCE=0.5 вдвое молчаливее (2 вдвое болтливее). Реплики с весом 8 и выше это не трогает.

Подстановки в текстах. {p} — место, о котором речь (при отрисовке станет «ты» или именем).
Глаголы при {p} не согласуются: «Автор: {p}», а не «{p} солгал». {n} и прочие — числа из партии.
Других фигурных скобок в текстах быть не должно: бот прогоняет строки через str.format.
"""
