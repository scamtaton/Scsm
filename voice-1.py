def _rand(op: OpState) -> random.Random:
    op.calls += 1
    return random.Random(zlib.crc32(f"{op.seed}:{op.calls}".encode()))


def _roll(op: OpState) -> float:
    return _rand(op).random()


def _pick(op: OpState, pool: str) -> str:
    items = POOLS[pool]
    used = op.used.setdefault(pool, [])
    left = [i for i in range(len(items)) if i not in used]
    if not left:
        used.clear()
        left = list(range(len(items)))
    fresh = [i for i in left if (pool, i) not in _RECENT]
    cand = fresh or left
    idx = cand[_rand(op).randrange(len(cand))]
    used.append(idx)
    _RECENT.append((pool, idx))
    return items[idx]


def _fill(text: str, kw: dict) -> str:
    for k, v in kw.items():
        text = text.replace("{" + k + "}", str(v))
    return text


def _say(op: OpState, pool: str, cycle: int, pri: int, chance: float = 1.0, **kw) -> str | None:
    """Решает, говорить ли. cycle: номер цикла выдачи (сколько выдач уже разрешено к этому моменту)."""
    if not ENABLED:
        return None
    if pri < 8:
        gap = 1 if pri >= 6 else 2
        base = ROUND_CAP + (1 if op.seats > 2 else 0)
        cap = base if pri >= 5 else base - 1                 # последнее место в курсе держим для важного
        if cycle - op.last_cycle < gap or op.round_n >= cap:
            return None
        chance = min(1.0, chance * CHANCE_SCALE)
    if pool in _PACED and cycle - op.last_series < SERIES_GAP:
        return None
    if chance < 1.0 and _roll(op) >= chance:
        return None
    text = _fill(_pick(op, pool), kw)
    if pool in _PACED:
        op.last_series = cycle
    op.last_cycle = cycle
    op.round_n += 1
    op.n_total += 1
    return text


def _top(op: OpState, cands: list, cycle: int) -> str | None:
    """Говорит самый важный из подходящих триггеров. Не выпал шанс (или сработал лимит): пробуется следующий
    по важности. За одну выдачу оператор говорит не больше одной реплики."""
    cands.sort(key=lambda t: -t[0])
    for pri, pool, chance, once, kw in cands:
        if once and once in op.fired:
            continue
        text = _say(op, pool, cycle, pri, chance, **kw)
        if text:
            if once:
                op.fired.add(once)
            return text
    return None


def _first(op: OpState, cands: list, cycle: int, penalize: bool = False) -> str | None:
    """Для концов курса и матча: пробует по очереди, говорит первый, у кого выпал шанс."""
    for pri, pool, chance, once, kw in cands:
        if once and once in op.fired:
            continue
        ch = chance * (0.4 if penalize and op.last_cycle == cycle else 1.0)
        text = _say(op, pool, cycle, pri, ch, **kw)
        if text:
            if once:
                op.fired.add(once)
            return text
    return None


