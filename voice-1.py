def on_round_start(op: OpState, charges) -> None:
    op.round_n = 0
    op.quiet = 0
    op.last_hit = -1
    op.hit_run = 0
    op.round_ex = 0
    op.round_dmg = [0] * op.seats
    mins = list(charges)[:op.seats]
    op.round_min = mins + [0] * (op.seats - len(mins))
    op.round_start = list(op.round_min)


def after_exchange(op: OpState, ex: Ex) -> str | None:
    """Выдача разрешена. Обновляет счётчики и, если есть повод, возвращает реплику."""
    d, r, n = ex.dealer, ex.receiver, op.seats
    lie = ex.label != ex.pill

    # ---------- счётчики (ведутся всегда, даже если оператор выключен)
    if not ex.auto:
        if lie:
            kind = "b2c" if ex.pill == BITTER else "c2b"
            op.lie_run[d] += 1
            op.true_run[d] = 0
            if op.kind[d] == kind:
                op.kind_n[d] += 1
            else:
                op.kind[d], op.kind_n[d] = kind, 1
            op.lies[d] += 1
        else:
            op.true_run[d] += 1
            op.lie_run[d] = 0
            op.kind[d], op.kind_n[d] = "", 0
            op.truths[d] += 1
        op.tails[d] = (op.tails[d] + ("L" if lie else "H"))[-4:]
        op.quick_run[d] = op.quick_run[d] + 1 if ex.d_think == 0 else 0
    choice = not (ex.forced or ex.void or ex.silent)
    if choice:
        if ex.take:
            op.take_run[r] += 1
            op.refuse_run[r] = 0
            op.takes[r] += 1
        else:
            op.refuse_run[r] += 1
            op.take_run[r] = 0
            op.refusals[r] += 1
    h = ex.hit if (ex.applied and ex.hit is not None) else None
    if h is not None:
        if op.last_hit == h:
            op.hit_run += 1
        else:
            op.last_hit, op.hit_run = h, 1
        op.quiet = 0
        op.round_dmg[h] += 1
    else:
        op.quiet += 1
        op.last_hit, op.hit_run = -1, 0
    op.round_ex += 1
    for s in range(min(n, len(ex.charges))):
        op.round_min[s] = min(op.round_min[s], ex.charges[s])

    if not ENABLED:
        return None

    # ---------- триггеры: (вес, пул, шанс, ключ «один раз», подстановки)
    cyc = ex.exchange_no - 1
    pd, pr = P(d), P(r)
    c: list = []

    if not ex.auto:
        if lie:
            if op.lie_run[d] == 5:
                c.append((9, "lie_run5", 1.0, None, {"p": pd}))
            elif op.kind_n[d] == 3 and op.kind[d] == "b2c":
                c.append((8, "lie_b2c3", 1.0, None, {"p": pd}))
            elif op.kind_n[d] == 3 and op.kind[d] == "c2b":
                c.append((8, "lie_c2b3", 1.0, None, {"p": pd}))
            elif op.lie_run[d] == 3:
                c.append((8, "lie_run3", 1.0, None, {"p": pd}))
            if sum(op.lies) == 1:
                c.append((5, "lie_first", 0.8, "lie_first", {"p": pd}))
        else:
            if op.true_run[d] == 5:
                c.append((9, "honest5", 1.0, None, {"p": pd}))
            elif op.true_run[d] == 3:
                c.append((7, "honest3", 0.6, None, {"p": pd}))
        if op.tails[d] in ("LHLH", "HLHL"):
            c.append((6, "alternating", 0.7, f"alt:{d}", {"p": pd}))
        if op.quick_run[d] == 3:
            c.append((3, "quick3", 0.6, None, {"p": pd}))

    if choice:
        if ex.take:
            if op.take_run[r] == 5:
                c.append((9, "take5", 1.0, None, {"p": pr}))
            elif op.take_run[r] == 3:
                c.append((7, "take3", 0.9, None, {"p": pr}))
        else:
            if op.refuse_run[r] == 5:
                c.append((9, "refuse5", 1.0, None, {"p": pr}))
            elif op.refuse_run[r] == 3:
                c.append((7, "refuse3", 0.9, None, {"p": pr}))

    if n == 2:
        if min(op.lie_run) >= 2:
            c.append((7, "mutual_lies", 0.8, "mutual_lies", {}))
        if min(op.true_run) >= 2:
            c.append((7, "mutual_truth", 0.8, "mutual_truth", {}))

    if h is not None:
        ch, mx = ex.charges[h], ex.max_charges[h]
        if ch == 1 and mx >= 2:
            c.append((7, "down_to_one", 0.8 if mx >= 3 else 0.2, f"one:{ex.round_no}:{h}", {"p": P(h)}))
        if n == 2 and all(x == 1 for x in ex.charges) and min(ex.max_charges) >= 2:
            c.append((7, "both_one", 0.6, f"both:{ex.round_no}", {}))
        if op.hit_run == 2 and mx >= 3 and not ex.killed:
            c.append((6, "hit2", 0.7, None, {"p": P(h)}))
        if ex.stake == 2 and not ex.hidden:
            c.append((9, "receipt_hit", 1.0, None, {"p": P(h)}) if ex.killed
                     else (6, "receipt_hit", 0.5, None, {"p": P(h)}))
        if ex.forced and ex.take and ex.pill == BITTER and not ex.hidden:
            c.append((4, "seal_hit", 0.5, None, {"p": P(h)}))
    else:
        if ex.fx == "tol":
            c.append((7, "t_tol", 0.6, None, {}))
        elif ex.fx == "shield" and ex.hit is not None:
            c.append((6, "t_shield", 0.9, None, {"p": P(ex.hit)}))
        elif ex.void:
            c.append((4, "void", 0.6, None, {}))
        elif ex.stake == 2 and not ex.hidden:
            c.append((4, "receipt_wasted", 0.6, None, {}))
        if op.quiet in (4, 7):
            c.append((3, "quiet", 0.6, None, {"n": op.quiet}))

    if ex.heard is not None and choice:
        wrong = (ex.pill == BITTER and ex.take) or (ex.pill == CLEAN and not ex.take)
        c.append((6, "rec_ignored", 0.7, None, {"p": pr}) if wrong else (4, "rec_acted", 0.5, None, {"p": pr}))

    if choice and not ex.auto:
        p_, l_, t_ = ex.pill, ex.label, ex.take
        if p_ == BITTER and l_ == BITTER:
            c.append((4, "took_warned", 0.22, None, {"p": pr}) if t_ else (4, "honest_punished", 0.22, None, {"p": pd}))
        elif p_ == BITTER and l_ == CLEAN:
            c.append((4, "fooled", 0.3, None, {"p": pr}) if t_ else (4, "caught", 0.3, None, {"p": pd}))
        elif p_ == CLEAN and l_ == CLEAN and not t_:
            c.append((4, "refused_truth", 0.25, None, {"p": pr}))
        elif p_ == CLEAN and l_ == BITTER:
            c.append((4, "scare_failed", 0.22, None, {"p": pr}) if t_ else (4, "scare_worked", 0.3, None, {"p": pr}))

    if not (ex.auto or ex.silent):
        t, who = max((ex.r_think, r), (ex.d_think, d))
        if t >= 20:
            c.append((3, "slow", 0.7, None, {"p": P(who), "n": t}))
    if ex.tray[1] == 1 and ex.tray[0] >= 3 and not ex.killed:      # tray = (чистых, горьких)
        c.append((3, "tray_one_bitter", 0.5, f"tob:{ex.round_no}", {}))
    if ex.auto:
        c.append((3, "auto_deal", 0.6, None, {"p": pd}))
    if ex.silent:
        c.append((3, "auto_take", 0.6, None, {"p": pr}))

    return _top(op, c, cyc)


def on_item(op: OpState, kind: str, seat: int, cycle: int) -> str | None:
    """Применён предмет. Только дуэль: в «Третьем» каталог бывает повреждён, и реплика выдала бы предмет."""
    pool = ITEM_POOL.get(kind)
    if not pool:
        return None
    return _say(op, pool, cycle, 5, 0.25, p=P(seat))


def on_reload(op: OpState, cycle: int) -> str | None:
    return _say(op, "reload", cycle, 3, 0.3)


def on_event(op: OpState, name: str, seat: int | None = None, cycle: int = 0, **kw) -> str | None:
    """Разовые события: тайм-аут дважды, выход, дверь, выбывший, пододвинутая таблетка."""
    pri, chance = EVENTS[name]
    if seat is not None:
        kw["p"] = P(seat)
    return _say(op, name, cycle, pri, chance, **kw)


def after_round(op: OpState, cycle: int, round_no: int, winners: list[int],
                decider: bool = False, special: str | None = None) -> str | None:
    """Курс закрыт. winners: места, которым записан курс. special: пул режима на троих."""
    if not ENABLED:
        return None
    pw = " и ".join(P(x) for x in winners)
    dmg = max(op.round_dmg[x] for x in winners)
    deep = any(op.round_min[x] == 1 and op.round_start[x] >= 3 for x in winners)   # падал до единицы с трёх и больше
    c: list = []
    if special:
        c.append((10, special, 0.6, None, {"p": pw}))
    if deep and op.round_ex >= 3:
        c.append((10, "round_comeback", 0.85, None, {"p": pw}))
    elif dmg == 0 and op.round_ex >= 3:
        c.append((10, "round_flawless", 0.85, None, {"p": pw}))
    if op.round_ex <= 3:
        c.append((10, "round_fast", 0.25, None, {"n": op.round_ex}))
    if decider:
        c.append((10, "decider", 0.8, None, {}))
    if op.round_ex >= 9:
        c.append((10, "round_long", 0.6, None, {"n": op.round_ex}))
    return _first(op, c, cycle, penalize=True)


def _summary_kw(op: OpState) -> dict:
    lies, truths = sum(op.lies), sum(op.truths)
    kw = {"deals": lies + truths, "lies": lies, "truths": truths, "refusals": sum(op.refusals),
          "takes": sum(op.takes), "diff": abs(lies - truths)}
    for i in range(op.seats):
        kw[f"s{i}"], kw[f"l{i}"], kw[f"t{i}"] = P(i), op.lies[i], op.truths[i]
    return kw


def after_match(op: OpState, cycle: int, winners: list[int], wins=None, trio: bool = False) -> str | None:
    """Матч окончен. wins: счёт курсов дуэли. trio: стол на троих."""
    if not ENABLED:
        return None
    c: list = []
    if trio:
        c.append((10, "t_end", 0.6, None, {}))
    else:
        w = winners[0]
        deals = op.lies[w] + op.truths[w]
        if op.lies[w] == 0 and op.truths[w] >= 3:
            c.append((10, "end_clean", 0.8, None, {"p": P(w)}))
        elif deals >= 5 and op.lies[w] / deals >= 0.6:
            c.append((10, "end_liar", 0.8, None, {"p": P(w)}))
        if wins and min(wins) == 0:
            c.append((10, "end_sweep", 0.6, None, {}))
        elif wins and sum(wins) == 3:
            c.append((10, "end_full", 0.5, None, {}))
    if sum(op.lies) + sum(op.truths) >= 4:
        pool = "summary2" if (not trio and op.seats == 2 and _roll(op) < 0.5) else "summary"
        c.append((10, pool, 0.45, None, _summary_kw(op)))
    return _first(op, c, cycle, penalize=True)
